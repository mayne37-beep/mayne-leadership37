import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {validateProject} from '../../assets/interactive-model.js';
const require=createRequire(import.meta.url),{JSDOM}=require('jsdom');
const html=await readFile(new URL('../../interactive-course-studio.html',import.meta.url),'utf8');
const template=JSON.parse(await readFile(new URL('../../assets/interactive-courses/critical-thinking-paul-elder.mayne-course.json',import.meta.url),'utf8'));
const dom=new JSDOM(html,{url:'https://www.mayneleadership.com/interactive-course-studio.html?course=paul-elder',pretendToBeVisual:true});
dom.window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};dom.window.HTMLDialogElement.prototype.close=function(){this.open=false;};
for(const name of ['window','document','localStorage','location','FileReader','ResizeObserver','requestAnimationFrame','cancelAnimationFrame'])if(dom.window[name])globalThis[name]=typeof dom.window[name]==='function'&&['requestAnimationFrame','cancelAnimationFrame'].includes(name)?dom.window[name].bind(dom.window):dom.window[name];
globalThis.fetch=async(url,options)=>{
  if(url==='/assets/interactive-courses/critical-thinking-paul-elder.mayne-course.json')return {ok:true,json:async()=>structuredClone(template)};
  return {ok:false,status:503,json:async()=>({error:'Project storage is not yet available.'})};
};
const timers=new Set(),originalTimeout=globalThis.setTimeout;
globalThis.setTimeout=(fn,ms,...args)=>{const id=originalTimeout(fn,ms,...args);timers.add(id);return id;};
const {editorForTesting}=await import('../../assets/interactive-author.js');
await new Promise(resolve=>setTimeout(resolve,10));
const opened=editorForTesting();assert.equal(opened.project.title,template.title);assert.notEqual(opened.project.id,template.id);
assert.equal(opened.project.scenes.length,8);assert.deepEqual(validateProject(opened.project),[]);assert.equal(opened.remote,false);assert.equal(opened.dirty,true);
assert.equal(JSON.parse(localStorage.getItem('mayne-interactive-draft-v1')).data.id,opened.project.id);
document.querySelector('[data-action="course-library"]').click();assert(document.getElementById('modal-body').textContent.includes('Paul–Elder'));
assert(document.querySelector('a[href="/critical-thinking-paul-elder.html"]'));
for(const timer of timers)clearTimeout(timer);globalThis.setTimeout=originalTimeout;
dom.window.close();console.log('PASS: Course library opens an editable copy and retains a recovery draft without depending on cloud project storage.');
