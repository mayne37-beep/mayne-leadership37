import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';

test('Root Cause Studio works from blank investigation to linked analysis and printable report',async()=>{
 const html=await readFile(new URL('../../root-cause-studio.html',import.meta.url),'utf8');
 const dom=new JSDOM(html,{url:'https://www.mayneleadership.com/root-cause-studio.html'});
 const previous={window:globalThis.window,document:globalThis.document,localStorage:globalThis.localStorage,FormData:globalThis.FormData,confirm:globalThis.confirm};
 Object.assign(globalThis,{window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,FormData:dom.window.FormData,confirm:()=>true});
 const proto=dom.window.HTMLDialogElement.prototype;
 proto.showModal=function(){this.open=true};
 proto.close=function(){this.open=false;this.dispatchEvent(new dom.window.Event('close'))};
 let printed=false;dom.window.print=()=>printed=true;
 const $=s=>dom.window.document.querySelector(s);
 const submit=()=>$('#editor-form').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
 const state=()=>JSON.parse(dom.window.localStorage.getItem('ml.root-cause.studio.v1'));
 const view=v=>$('[data-view="'+v+'"]').click();
 try{
  await import('../../assets/root-cause-studio.js?test=browser');
  assert.ok(state().cases.length===1);
  assert.equal(state().cases[0].causes.length,0);
  $('#case-title').value='Training backlog analysis';
  $('#case-title').dispatchEvent(new dom.window.Event('change',{bubbles:true}));
  assert.equal(state().cases[0].title,'Training backlog analysis');
  view('whys');
  assert.ok($('#why-add-form'), 'guided Why form appears');
  $('#why-answer').value='Scheduling conflict';
  $('#why-category').value='people';
  $('#why-add-form').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
  assert.equal(state().cases[0].causes.length,1);
  const causeId=state().cases[0].causes[0].id;
  assert.equal($('#why-parent').value,causeId, 'new cause selected as next Why parent');
  $('#why-answer').value='Late approval';
  $('#why-category').value='policy';
  $('#why-add-form').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
  assert.equal(state().cases[0].causes[1].parentId,causeId);
  view('evidence');
  $('[data-action=add-evidence]').click();
  $('[name=causeId]').value=causeId;
  $('[name=finding]').value='Approved schedules changed frequently';
  $('[name=source]').value='Class schedule register';
  submit();
  assert.equal(state().cases[0].evidence[0].causeId,causeId);
  view('pareto');
  $('[data-action=add-pareto]').click();
  $('[name=label]').value='Scheduling changes';
  $('[name=count]').value='30';
  submit();
  assert.equal(state().cases[0].pareto[0].count,30);
  view('fishbone');
  assert.match($('#fishbone-svg').outerHTML,/Late approval/);
  const dt={text:'',setData(key,value){this.text=value},getData(){return this.text}};
  const chip=dom.window.document.querySelector('[data-drag-cause="'+state().cases[0].causes[1].id+'"]');
  const start=new dom.window.Event('dragstart',{bubbles:true,cancelable:true});Object.defineProperty(start,'dataTransfer',{value:dt});chip.dispatchEvent(start);
  const zone=$('[data-bone-category=resources]');
  const drop=new dom.window.Event('drop',{bubbles:true,cancelable:true});Object.defineProperty(drop,'dataTransfer',{value:dt});zone.dispatchEvent(drop);
  assert.equal(state().cases[0].causes[1].category,'resources');
  view('actions');
  $('[data-action=add-solution]').click();
  $('[name=title]').value='Clarify scheduling approval';
  $('[name=causeId]').value=causeId;
  $('[name=impact]').value='4';
  $('[name=effort]').value='2';
  $('[name=confidence]').value='3';
  submit();
  assert.equal(state().cases[0].solutions[0].causeIds[0],causeId);
  $('#print-report').click();
  assert.equal(printed,true);
  assert.match($('#print-document').innerHTML,/Scheduling conflict/);
  $('#duplicate-case').click();
  assert.equal(state().cases.length,2);
  assert.notEqual(state().cases[0].id,state().cases[1].id);
  assert.equal(state().cases[0].causes[1].parentId,state().cases[0].causes[0].id);
 }finally{
  Object.assign(globalThis,previous);dom.window.close();
 }
});
