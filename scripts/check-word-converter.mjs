import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { createWorkerConverter } from '@matbee/libreoffice-converter/server';
import { PDFDocument, PDFName, decodePDFRawStream } from 'pdf-lib';
import { PdfStudioEngine } from '../assets/pdf-studio-engine.js';
import { makeSampleWord, validateWordFile, pdfFilename, pdfFilterOptions } from '../src/word-converter-core.js';

const require = createRequire(import.meta.url);
const sample = await makeSampleWord();
const checked = await validateWordFile(sample);
assert.equal(checked.extension, 'docx');
assert.equal(pdfFilename('Activity.docx'), 'Activity.pdf');
assert.equal(pdfFilename(''), 'Document.pdf');
await assert.rejects(validateWordFile({ name: 'file.pdf', size: 10 }), /Word/);
await assert.rejects(validateWordFile({ name: 'empty.docx', size: 0 }), /empty/);
await assert.rejects(validateWordFile({ name: 'large.docx', size: 26 * 1024 * 1024 }), /25 MB/);
await assert.rejects(validateWordFile({ name: 'broken.docx', size: 4, arrayBuffer: async () => new Uint8Array([80, 75, 0, 0]).buffer }), /damaged/);
console.log('PASS Word file validation and PDF filenames');
const deadline = setTimeout(() => { console.error('Conversion test exceeded five minutes.'); process.exit(1); }, 300000);
let converter, engine;
try {
  console.log('Initializing the shipping LibreOffice WASM engine...');
  converter = await createWorkerConverter({ wasmPath: path.join(path.dirname(require.resolve('@matbee/libreoffice-converter/package.json')), 'wasm') });
  engine = await PdfStudioEngine.create(await readFile(require.resolve('@embedpdf/pdfium/pdfium.wasm')));
  const converted = await converter.convert(checked.bytes, { inputFormat: 'docx', outputFormat: 'pdf', filterOptions: pdfFilterOptions() }, sample.name);
  const parsed = await PDFDocument.load(converted.data);
  assert.equal(parsed.getPageCount(), 2);
  engine.load(converted.data);
  assert.match(engine.pageText(0), /Facilitator preparation/);
  assert.match(engine.pageText(0), /Compare the evidence/);
  assert.match(engine.pageText(1), /Facilitator notes/);
  assert.equal(Math.round(engine.size(0).width), 612);
  assert.equal(Math.round(engine.size(0).height), 792);
  console.log('PASS DOCX to selectable two-page PDF with original dimensions and tables');
  const legacy = await converter.convert(checked.bytes, { inputFormat: 'docx', outputFormat: 'doc' }, sample.name);
  const legacyFile = { name: 'Sample.doc', size: legacy.data.length, arrayBuffer: async () => legacy.data.slice().buffer };
  const legacyChecked = await validateWordFile(legacyFile);
  const legacyPdf = await converter.convert(legacyChecked.bytes, { inputFormat: 'doc', outputFormat: 'pdf', filterOptions: pdfFilterOptions('high') }, legacyFile.name);
  engine.load(legacyPdf.data);
  assert.match(engine.pageText(0), /Facilitator preparation/);
  assert.equal(engine.info().count, 2);
  console.log('PASS legacy Word DOC conversion');
  const archive = await converter.convert(checked.bytes, { inputFormat: 'docx', outputFormat: 'pdf', filterOptions: pdfFilterOptions('high', true) }, sample.name);
  const archiveDoc = await PDFDocument.load(archive.data);
  const metadataRef = archiveDoc.catalog.get(PDFName.of('Metadata'));
  assert.ok(metadataRef, 'Archive PDF must include metadata');
  const metadata = new TextDecoder().decode(decodePDFRawStream(archiveDoc.context.lookup(metadataRef)).decode());
  assert.match(metadata, /pdfaid:part(?:="2"|>2<)/, 'Archive export must declare PDF/A part 2');
  console.log('PASS PDF/A-2 archive export');
  if (process.argv[2]) {
    const source = await readFile(process.argv[2]);
    const result = await converter.convert(source, { inputFormat: 'docx', outputFormat: 'pdf', filterOptions: pdfFilterOptions('high') }, path.basename(process.argv[2]));
    engine.load(result.data);
    assert.equal(engine.info().count, 2);
    assert.match(engine.pageText(0), /Café/);
    assert.match(engine.pageText(0), /Participant|Team discussion/);
    assert.match(engine.pageText(1), /End of conversion verification/);
    assert.equal(Math.round(engine.size(1).width), 792);
    assert.equal(Math.round(engine.size(1).height), 612);
    await writeFile(process.argv[2].replace(/\.docx$/i, '.pdf'), result.data);
    console.log('PASS independent Word document with image, headers, footer and landscape section');
  }
} finally {
  engine?.close();
  await converter?.destroy();
  clearTimeout(deadline);
}
console.log('Word-to-PDF checks passed.');
